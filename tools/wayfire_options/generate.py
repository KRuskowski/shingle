#!/usr/bin/env python3
"""Writes the table of Wayfire's options from its metadata/*.xml.

Every `<option>` of every `<plugin>` and `<object>` in Wayfire's metadata
directory becomes one tab-separated line: the section, the option, its
type, its default and, for a dynamic list, the name patterns of its
entries (`binding_*`). Shingle starts a Wayfire import from these defaults
and answers `wayfire/get-config-option` and `list-config-options` for
every option in the table (docs/design/wayfire-gaps.md, WG-2).

Usage, with a checkout of WayfireWM/wayfire at the commit the design pins:

  tools/wayfire_options/generate.py --metadata ../wayfire/metadata \\
      --commit 669bbe3647e798898982a2ff2cb172b6f626c12b \\
      --output crates/shingle-config/data/wayfire-options.tsv

The table is checked in; rerun this only to move to another commit, and
record the new commit in the design document.
"""

import argparse
import dataclasses
import glob
import os
import sys
import xml.etree.ElementTree as ElementTree

# The columns of every data line.
COLUMNS = ('section', 'option', 'type', 'default', 'entries')

@dataclasses.dataclass(frozen=True)
class Option:
  """One Wayfire option.

  Attributes:
    section: The plugin or object name, such as `core` or `output`.
    name: The option name.
    kind: Wayfire's type, such as `int`, `activator` or `dynamic-list`.
    default: The default text, as `<default>` holds it; empty for a
      dynamic list, which has none.
    entries: For a dynamic list, the prefixes of its entries in order;
      empty otherwise.
  """
  section: str
  name: str
  kind: str
  default: str
  entries: tuple = ()

def options_of(root):
  """The options of one parsed metadata file, in file order.

  Args:
    root: The `<wayfire>` element of a metadata file.

  Returns:
    A list of `Option`, for every `<option>` inside each `<plugin>` and
    `<object>`, including those nested in `<group>` and `<subgroup>`.

  Raises:
    ValueError: When an option has no name or type, or a default holds a
      tab or a line break, which the table cannot hold.
  """
  options = []
  for section in root:
    if section.tag not in ('plugin', 'object'):
      continue
    section_name = section.get('name')
    if not section_name:
      raise ValueError(f'a <{section.tag}> without a name')
    for element in section.iter('option'):
      name = element.get('name')
      kind = element.get('type')
      if not name or not kind:
        raise ValueError(f'an option of [{section_name}] lacks name or type')
      default = element.find('default')
      text = (default.text or '') if default is not None else ''
      if '\t' in text or '\n' in text:
        raise ValueError(f'[{section_name}] {name}: default {text!r} holds '
                         'a tab or a line break')
      entries = tuple(entry.get('prefix', '')
                      for entry in element.findall('entry'))
      options.append(Option(section_name, name, kind, text, entries))
  return options

def collect(paths):
  """The options of every metadata file in `paths`.

  Args:
    paths: Metadata file paths.

  Returns:
    The options sorted by section and then by name. A section defined in
    two files (Wayfire has two `vk-color-management`) contributes each
    option once.

  Raises:
    ValueError: When two files give one option different types or
      defaults.
  """
  found = {}
  for path in paths:
    for option in options_of(ElementTree.parse(path).getroot()):
      key = (option.section, option.name)
      if key in found and found[key] != option:
        raise ValueError(f'[{option.section}] {option.name} differs between '
                         'metadata files')
      found[key] = option
  return [found[key] for key in sorted(found)]

def render(options, commit):
  """The table text for `options`.

  Args:
    options: The options, in the order to write them.
    commit: The Wayfire commit the metadata comes from.

  Returns:
    The header comment, the column names and one line per option.
  """
  lines = [
      '# Wayfire\'s options, generated by tools/wayfire_options/generate.py',
      f'# from WayfireWM/wayfire {commit} metadata/*.xml. Do not edit.',
      '# ' + '\t'.join(COLUMNS),
  ]
  for option in options:
    entries = ' '.join(f'{prefix}*' for prefix in option.entries)
    lines.append('\t'.join((option.section, option.name, option.kind,
                            option.default, entries)))
  return '\n'.join(lines) + '\n'

def parse(text):
  """Reads a table written by `render` back into options.

  Args:
    text: The table text.

  Returns:
    The options in table order.

  Raises:
    ValueError: For a data line without five columns.
  """
  options = []
  for number, line in enumerate(text.splitlines(), 1):
    if not line or line.startswith('#'):
      continue
    columns = line.split('\t')
    if len(columns) != len(COLUMNS):
      raise ValueError(f'line {number}: {len(columns)} columns')
    section, name, kind, default, entries = columns
    prefixes = tuple(entry[:-1] for entry in entries.split())
    options.append(Option(section, name, kind, default, prefixes))
  return options

def main(argv=None):
  """Writes the table; returns the exit status."""
  parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
  parser.add_argument('--metadata', required=True,
                      help="Wayfire's metadata directory")
  parser.add_argument('--commit', required=True,
                      help='the Wayfire commit of that directory')
  parser.add_argument('--output', required=True, help='the table to write')
  arguments = parser.parse_args(argv)
  paths = sorted(glob.glob(os.path.join(arguments.metadata, '*.xml')))
  if not paths:
    print(f'generate.py: no *.xml in {arguments.metadata}', file=sys.stderr)
    return 1
  options = collect(paths)
  with open(arguments.output, 'w') as file:
    file.write(render(options, arguments.commit))
  print(f'generate.py: {len(options)} options from {len(paths)} files')
  return 0

if __name__ == '__main__':
  sys.exit(main())
